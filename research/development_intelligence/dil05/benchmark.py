"""Deterministic replay of 24 synthetic events against manual final-state labels."""
import argparse, hashlib,json,platform, time
from pathlib import Path
from planner import simulate
ROOT=Path(__file__).resolve().parent
POLICIES=('late_only','eager_unpinned','sha_pinned')

def run():
    frozen=json.loads((ROOT/'FREEZE.json').read_text(encoding='utf-8'))
    for path,sha in frozen['sha256'].items():
        if hashlib.sha256((ROOT/path).read_bytes()).hexdigest()!=sha:
            raise ValueError('freeze mismatch: '+path)
    output={'synthetic_only':True,'environment':platform.platform(),'python':platform.python_version(),'source_sha256':frozen['sha256'],'splits':{}}
    for split in ('development','holdout'):
        cases=json.loads((ROOT/'fixtures'/f'{split}.json').read_text(encoding='utf-8'))
        acc={p:{'correct_current_eligibility':0,'unsafe_reuse_cases':0,'batch_eligible':0,'post_ready_review_units':0,'overlap_window_seconds_sum':0,'total_review_units':0,'details':[]} for p in POLICIES}
        for c in cases:
            # Manual independent gold, not generated by the method being evaluated.
            for p in POLICIES:
                r=simulate(c,p);d=acc[p]
                right=r['current_valid']==c['gold_valid'];d['correct_current_eligibility']+=int(right)
                d['unsafe_reuse_cases']+=int(bool(r['unsafe_reuse_count']))
                d['total_review_units']+=r['review_units_total']
                if r['batch_all_green']:
                    d['batch_eligible']+=1
                    d['post_ready_review_units']+=r['post_ready_review_units']
                    d['overlap_window_seconds_sum']+=r['overlap_window_seconds_sum'] or 0
                d['details'].append({'id':c['id'],'right':right,'valid':r['current_valid'],'gold':c['gold_valid'], 'unsafe_reuse_count':r['unsafe_reuse_count'],'post_ready_review_units':r['post_ready_review_units'],'overlap_window_seconds_sum':r['overlap_window_seconds_sum']})
        output['splits'][split]=acc
    return output

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',required=True);a=p.parse_args()
    t=time.perf_counter();r=run();r['wall_seconds']=time.perf_counter()-t
    with open(a.output,'x',encoding='utf-8') as f:json.dump(r,f,indent=2,ensure_ascii=False)
    for split,by_method in r['splits'].items():
        print(split,{k:{z:v for z,v in s.items() if z!='details'} for k,s in by_method.items()})
