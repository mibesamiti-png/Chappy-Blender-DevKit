"""GLB-021: review-only history of three FIXED CBDK synthetic trial conditions.

This is not a generic addon runner or parameter optimizer. It consumes only
aggregate GLB-020 reports already generated by the allowlisted joint fixture.
It does not open GLBs, import addon source, edit source, or recommend settings.
Numerical comparisons represent sampled classified faces, never full geometry.
"""
from __future__ import annotations

import json
from pathlib import Path

from .glb_visual_property_review import _read_observations

TRIALS = ("narrow", "narrow_placebo", "identical")
EXPECTED_SIZES = (8, 48, 96)  # owned synthetic ball, capped shaft, socket
OUTPUT_JSON = "synthetic_trial_history.json"
OUTPUT_MARKDOWN = "synthetic_trial_history.md"


def _part_observations(report: dict) -> list[dict]:
    """Validate GLB-020 safety and return ONLY bounded anonymous aggregates."""
    parts, edge_rows, _ = _read_observations(report)
    if (len(parts) != 3 or tuple(row["triangle_count"] for row in parts)
            != EXPECTED_SIZES or len(edge_rows) != 3):
        raise ValueError("Expected the exact CBDK-owned three-part fixture")
    observed = []
    for part, edge in zip(parts, edge_rows):
        observed.append({
            "part_id": part["part_id"],
            "medium_faces": part["medium"],
            "high_faces": part["high"],
            "affected_faces": part["medium"] + part["high"],
            "observed_boundary_edges": edge["boundary_edges"],
        })
    return observed


def build_synthetic_trial_history(reports: dict) -> dict:
    """Compare a deliberate defect, an irrelevant placebo, and restoration.

    A test-only known generator control does not prove a user addon's source
    property is functional, nor that the numeric setting works for their model.
    """
    if (not isinstance(reports, dict) or set(reports) != set(TRIALS)):
        raise ValueError("Expected exactly three allowlisted synthetic trials")
    observed = {name: _part_observations(reports[name]) for name in TRIALS}
    defect = observed["narrow"]
    unrelated = observed["narrow_placebo"]
    restored = observed["identical"]
    # The fixture is a deliberately closed mesh with exactly one faulty socket
    # control. These are conditions on the synthetic generator, not inferred
    # semantic identities from an arbitrary GLB.
    if any(row["observed_boundary_edges"] != 0
           for rows in observed.values() for row in rows):
        raise ValueError("Unexpected open edges in closed synthetic trials")
    if (defect[2]["affected_faces"] < 1
            or unrelated[2]["affected_faces"] < 1
            or unrelated[0]["affected_faces"] < 1):
        raise ValueError("Synthetic defect or negative control not observed")
    if any(restored[i]["affected_faces"] != 0 for i in range(3)):
        raise ValueError("Synthetic restored baseline must have zero sampled errors")
    if any(defect[i]["affected_faces"] != 0 for i in (0, 1)):
        raise ValueError("Defective synthetic socket modified unrelated parts")
    if unrelated[1]["affected_faces"] != 0:
        raise ValueError("Negative control unexpectedly modifies synthetic shaft")

    def trial(name, label, diameter, ball_shifted):
        rows = observed[name]
        return {
            "trial_id": name,
            "condition": label,
            "allowlisted_fixture_controls": {
                "socket_opening_diameter": diameter,
                "ball_shifted": ball_shifted,
            },
            "parts": rows,
            "sampled_affected_faces_total": sum(x["affected_faces"] for x in rows),
            "exact_surface_equivalence_proven": False,
        }

    return {
        "kind": "cbdk_glb021_synthetic_trial_history_v1",
        "schema_version": 1,
        "status": "synthetic_review_only",
        "experiment_order": ["narrow", "narrow_placebo", "identical"],
        "trials": [
            trial("narrow", "deliberately_narrow_socket", 0.78, False),
            trial("narrow_placebo", "unrelated_ball_move_does_not_fix_socket",
                  0.78, True),
            trial("identical", "restore_known_synthetic_control", 1.70, False),
        ],
        "comparison": {
            "socket_affected_faces_before": defect[2]["affected_faces"],
            "socket_affected_faces_after_restoration": restored[2]["affected_faces"],
            "socket_affected_faces_after_unrelated_change": unrelated[2]["affected_faces"],
            "observed_socket_reduction_after_restoration":
                defect[2]["affected_faces"] - restored[2]["affected_faces"],
            "unrelated_change_did_not_fix_socket": True,
            "restoration_has_no_observed_regressions_in_other_parts": True,
        },
        "safety": {
            "fixture_generator_is_allowlisted": True,
            "user_addon_or_source_executed": False,
            "source_glbs_modified": False,
            "parameter_application_to_user_addon": False,
            "real_addon_causality_proven": False,
            "cross_file_part_identity_proven": False,
            "complete_surface_equivalence_proven": False,
            "parameter_value_recommended_to_user": False,
        },
    }


def render_synthetic_trial_history(history: dict) -> str:
    """Produce a local human-readable comparison; never output model metadata."""
    if (not isinstance(history, dict)
            or history.get("kind") != "cbdk_glb021_synthetic_trial_history_v1"
            or history.get("status") != "synthetic_review_only"
            or history.get("experiment_order") != list(TRIALS)
            or not isinstance(history.get("trials"), list)
            or len(history["trials"]) != 3):
        raise ValueError("Invalid synthetic trial history")
    safety = history.get("safety", {})
    if (not isinstance(safety, dict)
            or any(safety.get(k) is not False for k in (
                "user_addon_or_source_executed",
                "parameter_application_to_user_addon",
                "real_addon_causality_proven",
                "parameter_value_recommended_to_user",
                "complete_surface_equivalence_proven"))):
        raise ValueError("History cannot assert unsupported safety claims")
    lines = [
        "# GLB-021 固定合成モデルの変更履歴（自作テスト専用）",
        "",
        "※ **実際のアドオンの修正提案ではありません。** "
        "数値0.78/1.70はCBDK自作モデル専用で、使用者の推奨値ではありません。",
        "",
        "| 実験 | ソケット直径（合成） | ボール位置変更 | ソケットの黄＋赤 | ボールの黄＋赤 |",
        "| --- | ---: | :---: | ---: | ---: |",
    ]
    for trial in history["trials"]:
        parts = trial["parts"]
        if (not isinstance(parts, list) or len(parts) != 3
                or any(type(part.get("affected_faces")) is not int
                       or not 0 <= part["affected_faces"] <= EXPECTED_SIZES[i]
                       for i, part in enumerate(parts))):
            raise ValueError("Invalid synthetic part trial")
        control = trial["allowlisted_fixture_controls"]
        if (control.get("socket_opening_diameter") not in (0.78, 1.70)
                or type(control.get("ball_shifted")) is not bool):
            raise ValueError("Non-allowlisted synthetic control")
        lines.append(
            f'| `{trial["trial_id"]}` | '
            f'{control["socket_opening_diameter"]:.2f} | '
            f'{"あり" if control["ball_shifted"] else "なし"} | '
            f'{parts[2]["affected_faces"]} | {parts[0]["affected_faces"]} |'
        )
    lines.extend([
        "",
        "**観測**：ソケットの合成パラメータを元に戻すと差分が0。"
        "無関係なボール移動ではソケットの差分は解消しません。",
        "",
        "**限界**：この結果は三角面上のサンプリングによるものです。"
        "実ユーザーのアドオン設定の因果・正しい補正値・内部空洞の完全一致は未検証。",
        "",
        "ソースGLBの改変防止はCI側のSHA-256検査で別途確認します。",
        "",
    ])
    return "\n".join(lines)


def write_synthetic_trial_history(history: dict, directory: str | Path) -> tuple[Path, Path]:
    """Write two new local files; refuse symlinks or existing names."""
    dest = Path(directory)
    if dest.is_symlink() or not dest.is_dir():
        raise ValueError("Expected existing non-symlink local test directory")
    first, second = dest / OUTPUT_JSON, dest / OUTPUT_MARKDOWN
    for output in (first, second):
        if output.exists() or output.is_symlink():
            raise FileExistsError("Synthetic history output already exists")
    # Validate presentation before creating either file. Avoid writing a
    # partial report due to a failed validation.
    markdown = render_synthetic_trial_history(history)
    encoded = json.dumps(history, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    # No public network/file sync takes place. CI remains private local only.
    with first.open("x", encoding="utf-8") as stream:
        stream.write(encoded)
    with second.open("x", encoding="utf-8") as stream:
        stream.write(markdown)
    return first, second
